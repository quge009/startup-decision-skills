"""A1.6 — outcome_label_mapping function.

Maps a Crunchbase / opensporks row to an outcome label, used as ground
truth when comparing against framework verdict outputs in A5/A6 calibration.

Per A1.6 design (charter v5):
- This is a label-mapping function, not a dataset filter. EVERY input
  row gets a label (including INDETERMINATE / UNKNOWN). Filter v2's
  Tier 2/5 are dropped — the cohort definition is "rows that pass
  Tier 1 (AI category match) and Tier 3 (founded 2010-2026)".
- 8 labels: 4 positive variants, 2 negative variants, 1 equivocal,
  1 indeterminate, 1 unknown.

Snapshot date is set to 2024-08-01 per opensporks scrape window (Aug 2024).

Label definitions:

  POSITIVE_IPO              — ipo_status == "public". Clear win.
  POSITIVE_LATE_STAGE_FUNDED — operating_status == "active" AND last_funding_type
                              in {series_b, series_c, private_equity,
                              post_ipo_equity}. Strong success proxy: still
                              active and reached substantial financing.
  POSITIVE_ACQUIRED         — growth_insight_description mentions an
                              acquisition event ("acquired by", "has been
                              acquired", etc.). Crunchbase does not directly
                              expose "this company was acquired" as a
                              structured field — operating_status stays
                              "active" and ipo_status stays "private" after
                              private→private acquisition events. The
                              growth_insight_description free-text field
                              is the only signal for these acquisitions
                              in the opensporks dataset (auto-generated by
                              Crunchbase narrative; only ~2.4% of rows
                              have it, ~0.10% mention acquisition). Where
                              acquisition is detected, the company is
                              treated as POSITIVE per our framework's
                              success criterion (acquired by larger entity
                              counts as exit).
  EQUIVOCAL_DELISTED        — ipo_status == "delisted". Ambiguous outcome:
                              could be acquired-and-taken-private (positive)
                              OR voluntary delisting / squeeze-out (negative).
                              Kept separate from POSITIVE_IPO so downstream
                              evaluation can decide whether to count as
                              positive, negative, or filter out.
  NEGATIVE_CLOSED           — operating_status == "closed". Clear failure.
  NEGATIVE_NO_TRACTION      — operating_status == "active" AND
                              last_funding_type in early_stage set (empty,
                              pre_seed, seed, angel, equity_crowdfunding,
                              grant, non_equity_assistance) AND founded_on
                              ≥ 5 years before snapshot AND last_funding_at
                              ≥ 5 years before snapshot (or no funding event).
                              Silent death — never raised real money,
                              still listed but effectively defunct.
  INDETERMINATE             — operating_status == "active" but doesn't fit
                              POSITIVE_LATE_STAGE_FUNDED, POSITIVE_ACQUIRED,
                              or NEGATIVE_NO_TRACTION criteria. Outcome
                              still evolving (e.g. raised Series A 2 years
                              ago, still active — could go either way).
                              Whether to include in calibration is an
                              evaluation-stage decision (A5/A6).
  UNKNOWN                   — operating_status missing AND ipo_status
                              missing. Cannot determine anything; usually
                              indicates poor Crunchbase data quality.

Usage:
    from outcome_label import outcome_label_mapping
    label = outcome_label_mapping(row_dict)
"""

import re
from datetime import date

SNAPSHOT_DATE = date(2024, 8, 1)
NO_TRACTION_YEARS = 5

LATE_STAGE_FUNDING = frozenset({
    "series_b", "series_c", "private_equity", "post_ipo_equity",
})

EARLY_STAGE_FUNDING = frozenset({
    "",  # explicit empty
    "pre_seed", "seed", "angel",
    "equity_crowdfunding",
    "grant", "non_equity_assistance",
})

# Regex to detect acquisition events in growth_insight_description.
# Matches the company being acquired BY another entity. Phrases tested
# against the 2026-06-19 audit sample of acquisition mentions in
# opensporks growth_insight_description text.
ACQUIRED_RE = re.compile(
    r"\b(has been acquired|was acquired|got acquired|acquired by|acquisition by)\b",
    re.IGNORECASE,
)

VALID_LABELS = (
    "POSITIVE_IPO",
    "POSITIVE_LATE_STAGE_FUNDED",
    "POSITIVE_ACQUIRED",
    "EQUIVOCAL_DELISTED",
    "NEGATIVE_CLOSED",
    "NEGATIVE_NO_TRACTION",
    "INDETERMINATE",
    "UNKNOWN",
)


def _parse_date(s):
    if not s:
        return None
    s = s.strip()
    if len(s) < 10:
        return None
    try:
        return date(int(s[:4]), int(s[5:7]), int(s[8:10]))
    except (ValueError, TypeError):
        return None


def _years_between(later, earlier):
    if not later or not earlier:
        return None
    return (later - earlier).days / 365.25


def outcome_label_mapping(row):
    """Map a Crunchbase row dict to one of VALID_LABELS.

    Args:
      row: dict with at least these string-valued keys (any may be
        empty / missing):
          operating_status, ipo_status, last_funding_type,
          founded_on (YYYY-MM-DD or YYYY-MM or YYYY),
          last_funding_at (YYYY-MM-DD or empty),
          growth_insight_description (free-text, may be empty)

    Returns:
      One of VALID_LABELS.
    """
    op = (row.get("operating_status") or "").strip()
    ipo = (row.get("ipo_status") or "").strip()
    lft = (row.get("last_funding_type") or "").strip()
    growth_desc = row.get("growth_insight_description") or ""

    # Tier 1 — explicit IPO outcomes (highest precedence).
    if ipo == "public":
        return "POSITIVE_IPO"
    if ipo == "delisted":
        return "EQUIVOCAL_DELISTED"

    # Tier 2 — acquisition detected from growth_insight free-text. Placed
    # before "closed" because operating_status remains 'active' after
    # acquisition in Crunchbase (the acquired company is not deactivated),
    # and we want acquisition to take precedence over later tiers if the
    # signal exists.
    if ACQUIRED_RE.search(growth_desc):
        return "POSITIVE_ACQUIRED"

    # Tier 3 — explicit closure (clear failure).
    if op == "closed":
        return "NEGATIVE_CLOSED"

    # Tier 4 — active + late-stage funding (strong positive proxy).
    if op == "active" and lft in LATE_STAGE_FUNDING:
        return "POSITIVE_LATE_STAGE_FUNDED"

    # Tier 5 — active + early-stage / no funding + aged out: silent death.
    if op == "active" and lft in EARLY_STAGE_FUNDING:
        founded = _parse_date(row.get("founded_on"))
        last_funding = _parse_date(row.get("last_funding_at"))
        years_since_founding = _years_between(SNAPSHOT_DATE, founded)
        # If no funding event ever, use founding date as proxy for "last activity".
        years_since_last = (
            _years_between(SNAPSHOT_DATE, last_funding)
            if last_funding else years_since_founding
        )
        if (
            years_since_founding is not None
            and years_since_founding >= NO_TRACTION_YEARS
            and years_since_last is not None
            and years_since_last >= NO_TRACTION_YEARS
        ):
            return "NEGATIVE_NO_TRACTION"

    # Tier 6 — active but doesn't fit positive/negative criteria. Still evolving.
    if op == "active":
        return "INDETERMINATE"

    # Tier 7 — fallback for missing key fields.
    return "UNKNOWN"


# --- self-test on a small synthetic set ---

_TEST_CASES = [
    ({"operating_status": "active", "ipo_status": "public"}, "POSITIVE_IPO"),
    ({"operating_status": "active", "ipo_status": "delisted"}, "EQUIVOCAL_DELISTED"),
    ({"operating_status": "closed"}, "NEGATIVE_CLOSED"),
    ({"operating_status": "active", "last_funding_type": "series_b"}, "POSITIVE_LATE_STAGE_FUNDED"),
    ({"operating_status": "active", "last_funding_type": "private_equity"}, "POSITIVE_LATE_STAGE_FUNDED"),
    ({"operating_status": "active", "last_funding_type": "seed",
      "founded_on": "2015-01-01", "last_funding_at": "2015-06-01"}, "NEGATIVE_NO_TRACTION"),
    ({"operating_status": "active", "last_funding_type": "seed",
      "founded_on": "2022-01-01", "last_funding_at": "2022-06-01"}, "INDETERMINATE"),
    ({"operating_status": "active", "last_funding_type": "series_a",
      "founded_on": "2018-01-01", "last_funding_at": "2020-01-01"}, "INDETERMINATE"),
    ({"operating_status": "", "ipo_status": ""}, "UNKNOWN"),
    # Acquisition cases via growth_insight_description
    ({"operating_status": "active", "ipo_status": "private", "last_funding_type": "series_unknown",
      "growth_insight_description": "MosaicML may be growing as it has been acquired by Databricks for $1.3 billion..."},
     "POSITIVE_ACQUIRED"),
    ({"operating_status": "active", "ipo_status": "private",
      "growth_insight_description": "Company X was acquired by Big Co for an undisclosed sum."},
     "POSITIVE_ACQUIRED"),
    ({"operating_status": "active", "ipo_status": "private",
      "growth_insight_description": "Company Y has been acquiring smaller startups to expand its portfolio."},
     "INDETERMINATE"),  # "acquiring" should NOT match "acquired by"
]


def _self_test():
    fails = 0
    for i, (row, expected) in enumerate(_TEST_CASES, 1):
        got = outcome_label_mapping(row)
        ok = "OK" if got == expected else "FAIL"
        if got != expected:
            fails += 1
        print(f"  [{i}] {ok}: expected={expected!r:<30} got={got!r:<30}")
    for i, (verdict, label, expected) in enumerate(_BRIDGE_TEST_CASES, 1):
        got = verdict_outcome_evaluation_class(verdict, label)
        ok = "OK" if got == expected else "FAIL"
        if got != expected:
            fails += 1
        print(f"  [bridge-{i}] {ok}: ({verdict!r:<14}, {label!r:<28}) → {got!r:<26} (expected {expected!r})")
    total = len(_TEST_CASES) + len(_BRIDGE_TEST_CASES)
    print(f"\n  {total - fails}/{total} passed")
    return fails


# ============================================================================
# verdict ↔ outcome_label bridge — used by A5/A6 calibration to compute
# precision/recall over (committed prediction × committed truth) cells only.
# Hedged predictions and ambiguous truths are filtered, with proportions
# reported separately as diagnostic metrics.
# ============================================================================

# Crunchbase outcome_label → binary truth class.
SUCCESS_TRUTH_LABELS = frozenset({
    "POSITIVE_IPO",
    "POSITIVE_LATE_STAGE_FUNDED",
    "POSITIVE_ACQUIRED",
    "EQUIVOCAL_DELISTED",  # treated as SUCCESS per A1.6 design Decision 2 —
                            # most delistings are acquisition / take-private events
})

FAILURE_TRUTH_LABELS = frozenset({
    "NEGATIVE_CLOSED",
    "NEGATIVE_NO_TRACTION",
})

AMBIGUOUS_TRUTH_LABELS = frozenset({
    "INDETERMINATE",
    "UNKNOWN",
})

# Framework verdict labels.
COMMITTED_VERDICTS = frozenset({"PASS", "FAIL"})

HEDGED_VERDICTS = frozenset({
    "WARN",          # framework declined to commit to PASS / FAIL — hedged
    "OUT_OF_SCOPE",  # framework declared the candidate outside its evaluation
                     # taxonomy — neither prediction nor non-prediction
})

EVALUATION_CELL_TYPES = (
    "TP",                          # PASS  + SUCCESS truth
    "FP",                          # PASS  + FAILURE truth
    "TN",                          # WARN / FAIL / OOS + FAILURE truth (predicted-negative × FAILURE)
    "FN",                          # WARN / FAIL / OOS + SUCCESS truth (predicted-negative × SUCCESS)
    "FILTER_truth_ambiguous",      # any verdict + INDETERMINATE / UNKNOWN truth
    "UNEXPECTED",                  # diagnostic for invalid input
)


def verdict_outcome_evaluation_class(verdict, outcome_label):
    """Map a (framework verdict, Crunchbase outcome_label) pair into one
    of the EVALUATION_CELL_TYPES cells.

    **Evaluation definition:**
    binary precision / recall / F0.5 use predicted-positive = `PASS` and
    predicted-negative = `WARN` ∪ `FAIL` ∪ `OUT_OF_SCOPE` ∪ no-verdict. Truth-side
    `INDETERMINATE` / `UNKNOWN` are filtered.

    Truth-side commitment threshold (Decision 2): EQUIVOCAL_DELISTED is
    counted as SUCCESS — most delistings are acquisition / take-private
    events. This is a soft assumption; A5/A6 reports MAY include a
    sensitivity analysis that flips this to FAILURE to bound the metric.

    Args:
      verdict: one of "PASS", "WARN", "FAIL", "OUT_OF_SCOPE" (or empty/None for no-verdict)
      outcome_label: one of VALID_LABELS (8 outcome labels)

    Returns:
      One of EVALUATION_CELL_TYPES.
    """
    # Truth-side ambiguity always filters first — no point evaluating any
    # prediction against an outcome we can't determine.
    if outcome_label in AMBIGUOUS_TRUTH_LABELS:
        return "FILTER_truth_ambiguous"

    # Map outcome to binary truth.
    truth = "SUCCESS" if outcome_label in SUCCESS_TRUTH_LABELS else (
        "FAILURE" if outcome_label in FAILURE_TRUTH_LABELS else None
    )
    if truth is None:
        return "UNEXPECTED"

    # REPORT §2b: predicted-positive = PASS, predicted-negative = everything else
    # (WARN ∪ FAIL ∪ OUT_OF_SCOPE ∪ no-verdict).
    if verdict == "PASS":
        return "TP" if truth == "SUCCESS" else "FP"
    else:
        return "TN" if truth == "FAILURE" else "FN"


_BRIDGE_TEST_CASES = [
    # PASS × SUCCESS → TP
    ("PASS", "POSITIVE_IPO", "TP"),
    ("PASS", "POSITIVE_LATE_STAGE_FUNDED", "TP"),
    ("PASS", "POSITIVE_ACQUIRED", "TP"),
    ("PASS", "EQUIVOCAL_DELISTED", "TP"),  # Decision 2: delisted ≈ acquired
    # PASS × FAILURE → FP
    ("PASS", "NEGATIVE_CLOSED", "FP"),
    ("PASS", "NEGATIVE_NO_TRACTION", "FP"),
    # FAIL × FAILURE → TN
    ("FAIL", "NEGATIVE_CLOSED", "TN"),
    ("FAIL", "NEGATIVE_NO_TRACTION", "TN"),
    # FAIL × SUCCESS → FN
    ("FAIL", "POSITIVE_IPO", "FN"),
    ("FAIL", "POSITIVE_ACQUIRED", "FN"),
    # WARN / OUT_OF_SCOPE = predicted negative (REPORT §2b) → TN or FN
    ("WARN", "POSITIVE_IPO", "FN"),
    ("WARN", "POSITIVE_LATE_STAGE_FUNDED", "FN"),
    ("WARN", "NEGATIVE_CLOSED", "TN"),
    ("WARN", "NEGATIVE_NO_TRACTION", "TN"),
    ("OUT_OF_SCOPE", "POSITIVE_LATE_STAGE_FUNDED", "FN"),
    ("OUT_OF_SCOPE", "NEGATIVE_NO_TRACTION", "TN"),
    # Truth-side ambiguous → FILTER_truth_ambiguous regardless of prediction
    ("PASS", "INDETERMINATE", "FILTER_truth_ambiguous"),
    ("FAIL", "INDETERMINATE", "FILTER_truth_ambiguous"),
    ("WARN", "INDETERMINATE", "FILTER_truth_ambiguous"),
    ("OUT_OF_SCOPE", "UNKNOWN", "FILTER_truth_ambiguous"),
]


if __name__ == "__main__":
    import sys
    sys.exit(_self_test())
